namespace Sambient.Dsp.Wavetables.Recipes;

internal static class RecipeUtil
{
    public const double TwoPi = 2.0 * Math.PI;

    /// <summary>frame 0..127 -> 0..1</summary>
    public static double U(int frame) => frame / 127.0;

    public static double Lerp(double a, double b, double t) => a + (b - a) * t;
    public static double Clamp01(double x) => x < 0 ? 0 : x > 1 ? 1 : x;
    /// <summary>Hermite smoothstep 0..1 (zero slope at both ends).</summary>
    public static double Smooth(double x) { x = Clamp01(x); return x * x * (3.0 - 2.0 * x); }
    /// <summary>
    /// Piecewise-linear monotone warp of the HARMONIC position u (0..1) through equally spaced <paramref name="knots"/>
    /// (knots[0] = 0, knots[^1] = 1). Used to equalize how much the sound changes per frame: the knot tables were
    /// generated by measuring the cumulative spectral change of the unwarped recipe (see tests, Morph_ChangeIsSpreadOverTheRange).
    /// </summary>
    public static double Warp(double u, double[] knots)
    {
        double x = Clamp01(u) * (knots.Length - 1);
        int i = Math.Min(knots.Length - 2, (int)x);
        return Lerp(knots[i], knots[i + 1], x - i);
    }

    /// <summary>Exponential interpolation a -> b (a, b &gt; 0).</summary>
    public static double Exp(double a, double b, double t) => a * Math.Pow(b / a, t);

    /// <summary>Triangle wave of a phase in cycles (any real): 0 -> 0, 0.25 -> 1, 0.75 -> -1.</summary>
    public static double Tri(double cycles)
    {
        double p = cycles - Math.Floor(cycles);
        return p < 0.25 ? 4 * p : p < 0.75 ? 2 - 4 * p : 4 * p - 4;
    }

    /// <summary>Rising sawtooth -1..1 of a phase in cycles (jump at integers).</summary>
    public static double Saw(double cycles) => 2.0 * (cycles - Math.Floor(cycles)) - 1.0;

    /// <summary>Triangular wave-folder: reflects x back into [-1, 1] (identity inside).</summary>
    public static double FoldTri(double x) => (2.0 / Math.PI) * Math.Asin(Math.Sin(0.5 * Math.PI * x));

    /// <summary>Hard digital clip to +-1.</summary>
    public static double Clip(double x) => x < -1 ? -1 : x > 1 ? 1 : x;

    /// <summary>
    /// Fills the cycle by averaging <paramref name="f"/>(phase in cycles) over <paramref name="oversample"/> sub-samples
    /// per output sample (box filter): discontinuities become anti-aliased edges and move with sub-sample precision.
    /// </summary>
    public static void RenderOversampled(Span<float> cycle, int oversample, Func<double, double> f)
    {
        int n = cycle.Length;
        double inv = 1.0 / (n * (double)oversample);
        double norm = 1.0 / oversample;
        for (int i = 0; i < n; i++)
        {
            double s = 0;
            for (int k = 0; k < oversample; k++) s += f((i * (double)oversample + k + 0.5) * inv);
            cycle[i] = (float)(s * norm);
        }
    }

    /// <summary>Same as <see cref="RenderOversampled"/> but the sample is the box average centred on the sample (no half-sample shift of the waveform).</summary>
    public static void Render(Span<float> cycle, Func<double, double> f)
    {
        int n = cycle.Length;
        for (int i = 0; i < n; i++) cycle[i] = (float)f((double)i / n);
    }

    /// <summary>cycle[n] = sum_h amp[h] * sin(2 pi h n / N) for h = 1..amp.Length-1 (amp[0] ignored).</summary>
    public static void AdditiveSines(ReadOnlySpan<double> amp, Span<float> cycle)
    {
        int n = cycle.Length;
        var fft = Fft.GetShared(n);
        var re = new double[n];
        var im = new double[n];
        int hMax = Math.Min(amp.Length - 1, n / 2 - 1);
        for (int h = 1; h <= hMax; h++)
        {
            // a*sin(h t) = Im(a e^{iht}): inverse-FFT bins  X[h] = -i a N/2, X[N-h] = +i a N/2
            im[h] = -amp[h] * n * 0.5;
            im[n - h] = amp[h] * n * 0.5;
        }
        fft.Inverse(re, im);
        for (int i = 0; i < n; i++) cycle[i] = (float)re[i];
    }

    /// <summary>cycle[n] = sum_h amp[h] * sin(2 pi h n / N + phase[h]) for h = 1..amp.Length-1.</summary>
    public static void AdditivePhased(ReadOnlySpan<double> amp, ReadOnlySpan<double> phase, Span<float> cycle)
    {
        int n = cycle.Length;
        var fft = Fft.GetShared(n);
        var re = new double[n];
        var im = new double[n];
        int hMax = Math.Min(amp.Length - 1, n / 2 - 1);
        for (int h = 1; h <= hMax; h++)
        {
            // A sin(ht + p) = (A cos p) sin(ht) + (A sin p) cos(ht)
            double c = amp[h] * Math.Cos(phase[h]) * n * 0.5, s = amp[h] * Math.Sin(phase[h]) * n * 0.5;
            re[h] = s; im[h] = -c;
            re[n - h] = s; im[n - h] = c;
        }
        fft.Inverse(re, im);
        for (int i = 0; i < n; i++) cycle[i] = (float)re[i];
    }

    /// <summary>Multiplies harmonic h (1..N/2) of the cycle by <paramref name="gain"/>(h) in the frequency domain; DC is removed.</summary>
    public static void ShapeSpectrum(Span<float> cycle, Func<int, double> gain)
    {
        int n = cycle.Length;
        var fft = Fft.GetShared(n);
        var re = new double[n];
        var im = new double[n];
        for (int i = 0; i < n; i++) re[i] = cycle[i];
        fft.Forward(re, im);
        re[0] = 0; im[0] = 0;
        for (int h = 1; h < n / 2; h++)
        {
            double g = gain(h);
            re[h] *= g; im[h] *= g; re[n - h] *= g; im[n - h] *= g;
        }
        re[n / 2] = 0; im[n / 2] = 0;
        fft.Inverse(re, im);
        for (int i = 0; i < n; i++) cycle[i] = (float)re[i];
    }

    /// <summary>Gentle low-pass (2nd-order-like, -12 dB/oct beyond <paramref name="cutoffHarmonic"/>) to tame sharp edges.</summary>
    public static void Soften(Span<float> cycle, double cutoffHarmonic) =>
        ShapeSpectrum(cycle, h => { double r = h / cutoffHarmonic; return 1.0 / (1.0 + r * r); });

    /// <summary>Removes DC and scales the cycle to a peak of 1.0.</summary>
    public static void Finish(Span<float> cycle)
    {
        double mean = 0;
        foreach (var v in cycle) mean += v;
        mean /= cycle.Length;
        double peak = 0;
        for (int i = 0; i < cycle.Length; i++)
        {
            double v = cycle[i] - mean;
            cycle[i] = (float)v;
            double a = Math.Abs(v);
            if (a > peak) peak = a;
        }
        if (peak < 1e-12) return;
        float g = (float)(1.0 / peak);
        for (int i = 0; i < cycle.Length; i++) cycle[i] *= g;
    }

    /// <summary>Cubic Hermite (Catmull-Rom) read of a periodic cycle at a fractional position in cycles.</summary>
    public static double ReadCubic(ReadOnlySpan<float> cycle, double cycles)
    {
        int n = cycle.Length;
        double pos = (cycles - Math.Floor(cycles)) * n;
        int i = (int)pos; double f = pos - i;
        double y0 = cycle[(i - 1 + n) % n], y1 = cycle[i % n], y2 = cycle[(i + 1) % n], y3 = cycle[(i + 2) % n];
        double c1 = 0.5 * (y2 - y0), c2 = y0 - 2.5 * y1 + 2 * y2 - 0.5 * y3, c3 = 0.5 * (y3 - y0) + 1.5 * (y1 - y2);
        return ((c3 * f + c2) * f + c1) * f + y1;
    }

    /// <summary>
    /// Soft-edged mid-rise quantizer: x in [-1, 1] is quantized to <paramref name="levels"/> steps per unit (levels may be fractional,
    /// down to ~0.6 = a square). The step edges are smoothed over 18 % of a step, so stairs are born and move continuously
    /// when <paramref name="levels"/> is swept (no sudden plateaus, no amplitude jumps). Odd-symmetric; output scale ~ x.
    /// </summary>
    public static double Crush(double x, double levels)
    {
        double z = x * levels;
        return 0.5 * (Stair(z) - Stair(-z)) / levels;
    }

    private static double Stair(double z)
    {
        const double w = 0.18;
        double fl = Math.Floor(z);
        return fl + Smooth((z - fl - (1.0 - w)) / w);
    }

    /// <summary>
    /// Tames the crest factor of noise-like cycles: y = a tanh(x / a) with a = <paramref name="kSigma"/> x RMS, blended in by
    /// <paramref name="amount"/> (0 = untouched). Peak-normalized noise would otherwise be much quieter (RMS/peak ~ 0.25) than the tonal frames.
    /// </summary>
    public static void SoftLimit(Span<float> cycle, double kSigma, double amount)
    {
        if (amount <= 1e-6) return;
        double ms = 0;
        foreach (var v in cycle) ms += (double)v * v;
        double a = kSigma * Math.Sqrt(ms / cycle.Length);
        if (a < 1e-12) return;
        for (int i = 0; i < cycle.Length; i++)
            cycle[i] = (float)((1.0 - amount) * cycle[i] + amount * a * Math.Tanh(cycle[i] / a));
    }

    /// <summary>Normal-distributed random number (Box-Muller).</summary>
    public static double Gauss(Random rng)
    {
        double u1 = 1.0 - rng.NextDouble(), u2 = rng.NextDouble();
        return Math.Sqrt(-2.0 * Math.Log(u1)) * Math.Cos(TwoPi * u2);
    }

    /// <summary>
    /// Sine-series coefficient of harmonic h of a unit-peak basic shape: 0 sine, 1 triangle, 2 sawtooth, 3 square
    /// (the sine-series phase convention, so shapes can be cross-faded coefficient by coefficient).
    /// </summary>
    public static double SineCoef(int shape, int h)
    {
        switch (shape)
        {
            case 0: return h == 1 ? 1.0 : 0.0;
            case 1: return (h & 1) == 1 ? (8.0 / (Math.PI * Math.PI)) * (((h >> 1) & 1) == 0 ? 1.0 : -1.0) / ((double)h * h) : 0.0;
            case 2: return (2.0 / Math.PI) / h;
            default: return (h & 1) == 1 ? (4.0 / Math.PI) / h : 0.0;
        }
    }
}
